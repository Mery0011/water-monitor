"""SQLite locally; an external PostgreSQL database when configured."""
from contextlib import contextmanager
from functools import lru_cache
from pathlib import Path
import os
import sqlite3
import psycopg
from psycopg.rows import dict_row
from psycopg.conninfo import conninfo_to_dict

DATABASE_ERRORS = (sqlite3.Error, psycopg.Error)

SCHEMA = '''
CREATE TABLE IF NOT EXISTS contacts (
    apartment TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT NOT NULL,
    email TEXT NOT NULL, is_demo INTEGER NOT NULL CHECK(is_demo IN (0,1)), updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS runs (
    id TEXT PRIMARY KEY, mode TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS incidents (
    run_id TEXT NOT NULL REFERENCES runs(id), local_id INTEGER NOT NULL,
    payload TEXT NOT NULL, updated_at TEXT NOT NULL, PRIMARY KEY(run_id,local_id));
CREATE TABLE IF NOT EXISTS activity_stream (
    id {identity}, run_id TEXT NOT NULL REFERENCES runs(id), source TEXT NOT NULL,
    source_sequence INTEGER NOT NULL, payload TEXT NOT NULL, UNIQUE(run_id,source,source_sequence));
CREATE TABLE IF NOT EXISTS activity (
    run_id TEXT NOT NULL REFERENCES runs(id), sequence INTEGER NOT NULL,
    payload TEXT NOT NULL, PRIMARY KEY(run_id,sequence));
'''


def database_url():
    """Prefer environment configuration; Streamlit secrets are read server-side."""
    url = os.environ.get('WATER_MONITOR_DATABASE_URL','').strip()
    if not url:
        import streamlit as st
        from streamlit.errors import StreamlitSecretNotFoundError
        try:
            url = st.secrets.get('WATER_MONITOR_DATABASE_URL','').strip()
        except StreamlitSecretNotFoundError:
            pass
    if url and not url.startswith(('postgresql://','postgres://')):
        raise ValueError('WATER_MONITOR_DATABASE_URL must be a PostgreSQL URL.')
    return url


def database_path():
    override = os.environ.get('WATER_MONITOR_DB')
    return Path(override) if override else Path(__file__).resolve().parent/'data/water-monitor.sqlite3'


class PostgresConnection:
    """Translate parameter markers for the small shared query set only."""
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, params=()):
        return self.raw.execute(query.replace('?', '%s'),params)

    def begin_write(self):
        # Serialize workflow read/merge/write and audit sequence allocation,
        # including updates from other workers. Released at transaction end.
        self.raw.execute('SELECT pg_advisory_xact_lock(873204915)')


class SQLiteConnection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, params=()):
        return self.raw.execute(query,params)

    def begin_write(self):
        self.raw.execute('BEGIN IMMEDIATE')


def postgres_options(url):
    options = conninfo_to_dict(url)
    options.setdefault('sslmode','require')
    return options


@lru_cache(maxsize=4)
def initialize_postgres(url):
    with psycopg.connect(**postgres_options(url),connect_timeout=10,prepare_threshold=None) as db:
        db.execute('SELECT pg_advisory_xact_lock(873204915)')
        # Keep application tables outside Supabase's default public Data API schema.
        db.execute('CREATE SCHEMA IF NOT EXISTS water_monitor')
        db.execute('SET search_path TO water_monitor, pg_catalog')
        for statement in SCHEMA.format(identity='BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').split(';'):
            if statement.strip():
                db.execute(statement)


@contextmanager
def connection(path=None):
    # An explicit path always selects SQLite, also isolating tests from cloud credentials.
    url = database_url() if path is None and not os.environ.get('WATER_MONITOR_DB') else ''
    if url:
        initialize_postgres(url)
        with psycopg.connect(**postgres_options(url),connect_timeout=10,prepare_threshold=None,row_factory=dict_row) as db:
            db.execute('SET search_path TO water_monitor, pg_catalog')
            db.execute("SET LOCAL statement_timeout = '15s'")
            yield PostgresConnection(db)
        return
    path = Path(path) if path else database_path()
    path.parent.mkdir(parents=True,exist_ok=True)
    db = sqlite3.connect(path,timeout=10)
    db.row_factory = sqlite3.Row
    try:
        db.execute('PRAGMA foreign_keys=ON')
        db.execute('PRAGMA journal_mode=WAL')
        db.executescript(SCHEMA.format(identity='INTEGER PRIMARY KEY AUTOINCREMENT'))
        db.execute("""INSERT OR IGNORE INTO activity_stream (run_id,source,source_sequence,payload)
            SELECT run_id,CASE WHEN json_extract(payload,'$.source')='archive'
            THEN 'archive' ELSE 'simulation' END,sequence,payload FROM activity ORDER BY rowid""")
        db.commit()
        with db:
            yield SQLiteConnection(db)
    finally:
        db.close()
